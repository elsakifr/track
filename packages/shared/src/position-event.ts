/**
 * Canonical position-event contract (v1) — see docs/architecture.md §4.1.
 *
 * This is what every GPS source sends to `/ingest`. It deliberately contains no identity:
 * participant, device and race are derived by the server from the authenticated caller, and
 * `received_at` is set by the server. Strict objects reject any field not listed here, so a
 * client can neither claim another participant nor smuggle extra data into storage.
 */
import { z } from 'zod';

export const CONTRACT_VERSION = 1;

/** Maximum events per request. A longer offline backlog is sent as several batches. */
export const MAX_BATCH_SIZE = 500;

/** GPS sources in the MVP. New sources are added here when their integration is built. */
export const SOURCE_TYPES = ['mobile_app', 'simulator'] as const;

// Optional measurements may be omitted or null; both mean "not provided by this source".
const optional = (schema: z.ZodNumber) => schema.nullable().optional();

export const positionEventSchema = z.strictObject({
  /** Per event (not per batch): an offline queue can hold events from before and after an app update. */
  contract_version: z.literal(CONTRACT_VERSION),
  /**
   * Random UUID v4 generated by the source. A deduplication identifier only — never an
   * authentication or authorization mechanism. The server deduplicates per participant.
   */
  event_id: z.uuid({ version: 'v4' }),
  source_type: z.enum(SOURCE_TYPES),
  /** When the fix was taken, by the device clock. Must include a timezone (`Z` or an offset). */
  recorded_at: z.iso.datetime({ offset: true }),
  /** WGS84 degrees. */
  lat: z.number().min(-90).max(90),
  lon: z.number().min(-180).max(180),
  /** Horizontal accuracy in metres. */
  accuracy_m: optional(z.number().min(0)),
  /** Loose bounds that only reject obviously broken values. */
  altitude_m: optional(z.number().min(-1000).max(10000)),
  speed_mps: optional(z.number().min(0).max(100)),
  /** 0 ≤ heading < 360. Sources that report "unknown" as -1 must send null instead. */
  heading_deg: optional(z.number().min(0).lt(360)),
});

/** A request body as sent by a source: 1 to MAX_BATCH_SIZE valid events. */
export const positionBatchSchema = z.strictObject({
  events: z.array(positionEventSchema).min(1).max(MAX_BATCH_SIZE),
});

export type SourceType = (typeof SOURCE_TYPES)[number];
export type PositionEvent = z.infer<typeof positionEventSchema>;
export type PositionBatch = z.infer<typeof positionBatchSchema>;

/** A validation problem. Never contains input values, so positions cannot leak into logs or responses. */
export type ValidationIssue = { path: PropertyKey[]; message: string };
export type RejectedEvent = { index: number; issues: ValidationIssue[] };
export type ParsedPositionBatch =
  | { ok: false; issues: ValidationIssue[] }
  | { ok: true; accepted: PositionEvent[]; rejected: RejectedEvent[] };

const batchEnvelopeSchema = z.strictObject({
  events: z.array(z.unknown()).min(1).max(MAX_BATCH_SIZE),
});

const toIssues = (error: z.ZodError): ValidationIssue[] =>
  error.issues.map(({ path, message }) => ({ path, message }));

/**
 * Validates a batch on the server: first the envelope, then each event on its own, so one
 * invalid event does not reject the valid ones.
 *
 * This is payload validation only. Authentication, authorization and request-level checks
 * (e.g. request size) must succeed BEFORE this is called, and nothing may be accepted or
 * stored if they fail.
 */
export function parsePositionBatch(input: unknown): ParsedPositionBatch {
  const envelope = batchEnvelopeSchema.safeParse(input);
  if (!envelope.success) return { ok: false, issues: toIssues(envelope.error) };

  const accepted: PositionEvent[] = [];
  const rejected: RejectedEvent[] = [];
  envelope.data.events.forEach((event, index) => {
    const result = positionEventSchema.safeParse(event);
    if (result.success) accepted.push(result.data);
    else rejected.push({ index, issues: toIssues(result.error) });
  });
  return { ok: true, accepted, rejected };
}
